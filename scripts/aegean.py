#!/usr/bin/env python3
"""Cut the Aegean out of Natural Earth's land polygons and write it as SVG paths.

    python3 scripts/aegean.py ne_50m_land.geojson

Natural Earth (naturalearthdata.com) is in the public domain. The output,
src/content/aegean.ts, holds simplified outlines for lon 19.5-32.5 E, lat 34.6-42 N
in an equirectangular projection scaled by cos(38 degrees).
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

LON0, LON1, LAT0, LAT1 = 19.5, 32.5, 34.6, 42.0
K = 60.0
COS = math.cos(math.radians(38))
TOLERANCE = 0.6


def project(lon: float, lat: float) -> tuple[float, float]:
    return ((lon - LON0) * COS * K, (LAT1 - lat) * K)


def clip(ring: list[tuple[float, float]]) -> list[tuple[float, float]]:
    """Sutherland-Hodgman against the window's four edges."""
    edges = [
        (lambda p: p[0] >= LON0, lambda a, b: inter_x(a, b, LON0)),
        (lambda p: p[0] <= LON1, lambda a, b: inter_x(a, b, LON1)),
        (lambda p: p[1] >= LAT0, lambda a, b: inter_y(a, b, LAT0)),
        (lambda p: p[1] <= LAT1, lambda a, b: inter_y(a, b, LAT1)),
    ]
    out = ring
    for inside, cut in edges:
        if not out:
            break
        src, out = out, []
        prev = src[-1]
        for cur in src:
            if inside(cur):
                if not inside(prev):
                    out.append(cut(prev, cur))
                out.append(cur)
            elif inside(prev):
                out.append(cut(prev, cur))
            prev = cur
    return out


def inter_x(a, b, x):
    t = (x - a[0]) / (b[0] - a[0])
    return (x, a[1] + t * (b[1] - a[1]))


def inter_y(a, b, y):
    t = (y - a[1]) / (b[1] - a[1])
    return (a[0] + t * (b[0] - a[0]), y)


def simplify(points, tol):
    if len(points) < 3:
        return points
    a, b = points[0], points[-1]
    dx, dy = b[0] - a[0], b[1] - a[1]
    norm = math.hypot(dx, dy) or 1.0
    far, index = -1.0, 0
    for i in range(1, len(points) - 1):
        p = points[i]
        d = abs(dy * p[0] - dx * p[1] + b[0] * a[1] - b[1] * a[0]) / norm
        if d > far:
            far, index = d, i
    if far <= tol:
        return [a, b]
    return simplify(points[: index + 1], tol)[:-1] + simplify(points[index:], tol)


def main() -> None:
    data = json.loads(Path(sys.argv[1]).read_text())
    paths = []
    for feature in data["features"]:
        geom = feature["geometry"]
        polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
        for poly in polys:
            ring = [tuple(p) for p in poly[0]]
            cut = clip(ring)
            if len(cut) < 3:
                continue
            ring_pts = [project(*p) for p in cut]
            if len(ring_pts) > 1 and ring_pts[0] == ring_pts[-1]:
                ring_pts = ring_pts[:-1]
            # A closed ring has no baseline; simplify its two halves separately.
            mid = len(ring_pts) // 2
            pts = simplify(ring_pts[: mid + 1], TOLERANCE)[:-1] + simplify(ring_pts[mid:] + ring_pts[:1], TOLERANCE)[:-1]
            if len(pts) < 3:
                continue
            xs = [p[0] for p in pts]
            ys = [p[1] for p in pts]
            if (max(xs) - min(xs)) * (max(ys) - min(ys)) < 4:
                continue
            paths.append("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + "Z")
    width, height = project(LON1, LAT0)
    body = (
        "// Generated by scripts/aegean.py from Natural Earth 1:50m land (public domain). Do not edit.\n"
        f"export const AEGEAN = {{ width: {width:.1f}, height: {height:.1f}, land: {json.dumps(paths)} }};\n\n"
        "/** Equirectangular projection used for the outlines above. */\n"
        f"export function project(lon: number, lat: number): [number, number] {{\n"
        f"  return [(lon - {LON0}) * {COS:.6f} * {K}, ({LAT1} - lat) * {K}];\n}}\n"
    )
    Path("src/content/aegean.ts").write_text(body)
    print(f"{len(paths)} outlines, {len(body) // 1024} KB, {width:.0f} x {height:.0f}")


if __name__ == "__main__":
    main()
